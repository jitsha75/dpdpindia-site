#!/usr/bin/env bash
# Gujarat Health Integrated Data Platform - start script (macOS / Linux; works with the stock bash 3.2 on macOS)
#
#   ./start.sh              start the platform (first run builds 3 images and seeds synthetic data: ~5-10 minutes)
#   ./start.sh --reset      wipe all demo databases and start again from the original story
#   ./start.sh --rebuild    rebuild the images (done automatically when the code has changed)
#   ./start.sh --full       also start the optional SSO (Keycloak), LLM (Ollama) and object store (MinIO) containers
#   ./start.sh --no-open    do not open the browser
#   ./start.sh --port 8096  use another port for the gateway (default 8095)
#
set -u
cd "$(dirname "$0")" || exit 1
RESET=0; REBUILD=0; OPEN=1; FULL=0; PORT_ARG=""
if [ -t 1 ]; then B=$'\033[1m'; G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; N=$'\033[0m'; else B=""; G=""; Y=""; R=""; N=""; fi
say()  { printf '%s\n' "${B}==>${N} $*"; }
ok()   { printf '%s\n' "${G} ok${N}  $*"; }
warn() { printf '%s\n' "${Y}warn${N} $*"; }
die()  { printf '%s\n' "${R}error${N} $*" >&2; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --reset) RESET=1 ;; --rebuild) REBUILD=1 ;; --no-open) OPEN=0 ;; --full) FULL=1 ;;
    --port) shift; PORT_ARG="${1:-}" ;;
    -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac; shift
done

# ---------------------------------------------------------------- 1. Docker
command -v docker >/dev/null 2>&1 || die "Docker is not installed. Install Docker Desktop for Mac (Apple silicon), OrbStack or Colima, then run ./start.sh again."
STATE_FILE=".runtime_started_by_start_sh"
if ! docker info >/dev/null 2>&1; then
  say "Docker is not running - starting it..."
  if [ "$(uname -s)" = "Darwin" ]; then
    if [ -d /Applications/OrbStack.app ]; then open -a OrbStack; echo orbstack > "$STATE_FILE"
    elif [ -d /Applications/Docker.app ]; then open -a Docker; echo docker-desktop > "$STATE_FILE"
    elif command -v colima >/dev/null 2>&1; then colima start --cpu 4 --memory 8 >/dev/null 2>&1; echo colima > "$STATE_FILE"
    else die "Start Docker Desktop (or OrbStack / Colima) and run ./start.sh again."; fi
  else die "Start the Docker daemon and run ./start.sh again."; fi
  n=0; until docker info >/dev/null 2>&1; do n=$((n+1)); [ $n -gt 60 ] && die "Docker did not become ready within 3 minutes."; printf '.'; sleep 3; done; printf '\n'
else rm -f "$STATE_FILE"; fi
ok "Docker is running"
docker compose version >/dev/null 2>&1 || die "'docker compose' (v2) is not available. Update Docker Desktop."
MEM_BYTES="$(docker info --format '{{.MemTotal}}' 2>/dev/null || echo 0)"
if [ "${MEM_BYTES:-0}" -gt 0 ] 2>/dev/null; then
  MEM_GB=$(( MEM_BYTES / 1073741824 ))
  if [ "$MEM_GB" -lt 5 ]; then warn "Docker has only ~${MEM_GB} GB. The platform needs about 4 GB (10 GB with --full). Raise it in Docker Desktop > Settings > Resources."
  else ok "Docker has ~${MEM_GB} GB of memory (the platform uses about 3-4 GB)"; fi
fi

# ---------------------------------------------------------------- 2. configuration
rand_hex() { if command -v openssl >/dev/null 2>&1; then openssl rand -hex "$1"; else LC_ALL=C tr -dc 'a-f0-9' < /dev/urandom | head -c $(( $1 * 2 )); fi; }
if [ ! -f .env ]; then
  if docker volume inspect gj-health-platform_pgdata >/dev/null 2>&1 && [ $RESET -eq 0 ]; then
    die "Found existing demo databases but no .env file (their password and keys are lost). Run ./start.sh --reset."
  fi
  say "Creating .env with fresh random keys (kept on this machine only)"
  { echo "# generated by start.sh - do not share"; echo "POSTGRES_PASSWORD=$(rand_hex 12)"; echo "JWT_SECRET=$(rand_hex 24)"
    echo "PLATFORM_TOKEN_KEY=$(rand_hex 24)"; echo "TENANT_KEY=$(rand_hex 24)"; echo "LEDGER_KEY=$(rand_hex 24)"
    echo "DEMO_STEPUP_PASSWORD=Gujarat@2026"; echo "PORT=8095"; } > .env
  chmod 600 .env
fi
set -a; . ./.env; set +a
PORT="${PORT_ARG:-${PORT:-8095}}"
port_busy() { command -v lsof >/dev/null 2>&1 && lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }
if [ -z "$(docker ps -q --filter name=^ghip-gateway$)" ] && port_busy "$PORT"; then
  p=$PORT; while port_busy "$p"; do p=$((p+1)); done; warn "Port $PORT is busy - using $p"; PORT=$p
fi
export PORT
{ grep -v '^PORT=' .env; echo "PORT=$PORT"; } > .env.tmp && mv .env.tmp .env && chmod 600 .env
sed "s/\"8095:80\"/\"$PORT:80\"/" docker-compose.yml > .compose.run.yml
DC="docker compose -f .compose.run.yml"
[ $FULL -eq 1 ] && DC="$DC --profile full"

# ---------------------------------------------------------------- 3. images (rebuilt automatically when the code changes)
hash_of() { { for d in "$@"; do find "$d" -type f ! -name '*.pyc' ! -path '*/__pycache__/*' ! -path '*/node_modules/*' ! -path '*/dist/*' ! -name '*.whl' 2>/dev/null; done | LC_ALL=C sort | while read -r f; do printf '%s\n' "$f"; cat "$f"; done; } |
  { if command -v shasum >/dev/null 2>&1; then shasum -a 256; else sha256sum; fi; } | cut -c1-16; }
img_label() { docker image inspect -f '{{ index .Config.Labels "org.ghip.code-hash" }}' "$1" 2>/dev/null; }
if [ $RESET -eq 1 ]; then say "Resetting: removing containers and all demo databases"; $DC down -v --remove-orphans >/dev/null 2>&1 || true; fi
for f in images/ghip-images.tar.gz; do [ -f "$f" ] && ! docker image inspect ghip/py-services:1.0 >/dev/null 2>&1 && { say "Loading images from $f (offline bundle)"; docker load -i "$f"; }; done
build() {  # image, hash, context, dockerfile
  if [ $REBUILD -eq 1 ] || [ "$(img_label "$1")" != "$2" ]; then
    say "Building $1 (first time or code changed; a few minutes)"
    docker build --label "org.ghip.code-hash=$2" -t "$1" -f "$4" "$3" || die "build of $1 failed - check your internet connection and run ./start.sh again"
  else ok "$1 is up to date"; fi
}
build ghip/py-services:1.0 "$(hash_of $(ls -d services/*/ | grep -v dpdp-compliance) services/Dockerfile services/requirements-all.txt)" services services/Dockerfile
build ghip/dpdp-compliance:1.0 "$(hash_of services/dpdp-compliance-service)" services/dpdp-compliance-service services/dpdp-compliance-service/Dockerfile
build ghip/gateway:1.0 "$(hash_of frontend gateway)" . gateway/Dockerfile

# ---------------------------------------------------------------- 4. start
say "Starting $(grep -c '^  [a-z0-9-]*:$' docker-compose.yml) containers"
$DC up -d --remove-orphans || die "docker compose up failed"
say "Waiting for the services to seed synthetic data (first start: several minutes; later starts: about a minute)"
total=$(docker ps -a --filter name=^ghip- --format '{{.Names}}' | grep -v -e postgres -e gateway | wc -l | tr -d ' ')
n=0
while :; do
  healthy=$(docker ps --filter name=^ghip- --filter health=healthy --format '{{.Names}}' | wc -l | tr -d ' ')
  printf '\r   %s of %s services healthy ' "$healthy" "$total"
  [ "$healthy" -ge "$total" ] && break
  n=$((n+1)); [ $n -gt 180 ] && { printf '\n'; warn "Some services are still starting: $(docker ps --filter name=^ghip- --filter health=starting --format '{{.Names}}' | tr '\n' ' ')"; break; }
  sleep 5
done
printf '\n'
URL="http://localhost:$PORT"
ok "Platform ready at ${B}$URL${N}"
echo "   Sign in by choosing a persona. Decryption password: ${DEMO_STEPUP_PASSWORD:-Gujarat@2026}"
echo "   Stop with ./stop.sh   (./stop.sh --quit-docker also quits Docker to free memory)"
if [ $OPEN -eq 1 ]; then (command -v open >/dev/null && open "$URL") || (command -v xdg-open >/dev/null && xdg-open "$URL") || true; fi
