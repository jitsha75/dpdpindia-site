#!/usr/bin/env python3
"""Merge every standard service's requirements.txt into services/requirements-all.txt for the shared image.
When two services pin different versions of a package, the higher version wins (reported)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "services"
pins, conflicts = {}, []


def key(v):
    return [int(x) if x.isdigit() else x for x in re.split(r"[.\-]", v)]


for req in sorted(ROOT.glob("*/requirements.txt")):
    if req.parent.name == "dpdp-compliance-service":
        continue
    for line in req.read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        m = re.match(r"^([A-Za-z0-9_.\-]+)(\[[^\]]+\])?\s*(==|>=)?\s*([^\s;]+)?", line)
        name, extra, op, ver = m.group(1).lower().replace("_", "-"), m.group(2) or "", m.group(3), m.group(4)
        cur = pins.get(name)
        if not cur:
            pins[name] = (extra, op, ver)
            continue
        e2 = cur[0] if len(cur[0]) >= len(extra) else extra
        if ver and cur[2] and ver != cur[2]:
            conflicts.append(f"{name}: {cur[2]} vs {ver} ({req.parent.name})")
            pins[name] = (e2, "==", max(ver, cur[2], key=key))
        else:
            pins[name] = (e2, cur[1] or op, cur[2] or ver)
out = [f"{n}{e}{(op or '') + (v or '')}" for n, (e, op, v) in sorted(pins.items())]
(ROOT / "requirements-all.txt").write_text("# GENERATED by tools/merge_requirements.py\n" + "\n".join(out) + "\n")
print(len(out), "packages;", "conflicts resolved to the higher pin:" if conflicts else "no conflicts", *conflicts, sep="\n  ")
