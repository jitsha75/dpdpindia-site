def nginx():
    loc = []
    for name in gjref.SERVICES:
        port = gjref.SERVICES[name][0]
        var = name.replace("-", "_")
        loc.append(f"""    location /api/{name}/ {{
        set $up_{var} http://{name}:{port};
        rewrite ^/api/{name}/(.*)$ /$1 break;
        proxy_pass $up_{var};
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_read_timeout 180s;
    }}""")
    conf = f"""# GENERATED by tools/gen_stack.py. One origin for the platform: the React shell, every microservice under
# /api/<service>/ (prefix stripped), and Module B's own screens under /dpdp-app/.
server {{
    listen 80;
    server_name _;
    resolver 127.0.0.11 valid=10s ipv6=off;
    client_max_body_size 25m;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy same-origin always;
    root /usr/share/nginx/html;

{chr(10).join(loc)}

    location /dpdp-app/ {{
        set $up_dpdp_app http://dpdp-compliance-service:8040;
        rewrite ^/dpdp-app/(.*)$ /$1 break;
        proxy_pass $up_dpdp_app;
        proxy_set_header Host $host;
        proxy_read_timeout 180s;
    }}
    location = /dpdp-app {{ return 301 /dpdp-app/; }}

    location / {{
        try_files $uri $uri/ /index.html;
    }}
}}
"""
    (ROOT / "gateway" / "nginx.conf").write_text(conf)


def initsql():
    d = ROOT / "postgres-init"
    d.mkdir(exist_ok=True)
    lines = ["-- GENERATED by tools/gen_stack.py: one database per microservice."]
    lines += [f"CREATE DATABASE {db};" for db in sorted(set(DB.values()))]
    for v in VECTOR:
        lines += [f"\\connect {v}", "CREATE EXTENSION IF NOT EXISTS vector;"]
    (d / "01-databases.sql").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    missing = [s for s in gjref.SERVICES if s not in DB]
    if missing:
        sys.exit(f"no database configured for {missing}")
    compose(); nginx(); initsql()
    print(f"generated compose ({len(gjref.SERVICES)} services), gateway/nginx.conf, postgres-init/01-databases.sql")
